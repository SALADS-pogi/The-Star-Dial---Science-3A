// Bundle reviewed source data for offline / file:// use. No runtime network API.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const iau = require('../atlas-iau.json');
const boundaries = require('../atlas-boundaries.json');
const learning = require('../atlas-learning.json');
const {observer} = require('../observer.js');
const sunPath = new Set(['Ari','Tau','Gem','Cnc','Leo','Vir','Lib','Sco','Oph','Sgr','Cap','Aqr','Psc']);
const entries = Object.entries(iau.constellations).map(([abbr, item]) => {
  const bounds = boundaries.constellations[abbr];
  if (!bounds) throw new Error(`Missing boundaries: ${abbr}`);
  // Vertex extrema alone omit the pole enclosed by these two constellations.
  const minDec = abbr === 'Oct' ? -90 : bounds.minDeclination;
  const maxDec = abbr === 'UMi' ? 90 : bounds.maxDeclination;
  const charts = item.charts.map(chart => {
    const localPath = 'assets/atlas/' + path.basename(new URL(chart.gifUrl).pathname);
    const bytes = fs.readFileSync(path.join(root, localPath));
    if (!/^GIF8[79]a$/.test(bytes.subarray(0, 6).toString())) throw new Error(`Invalid chart: ${localPath}`);
    return {...chart, localPath, width:bytes.readUInt16LE(6), height:bytes.readUInt16LE(8)};
  });
  return {...item, charts, minDec, maxDec, sunPath:sunPath.has(abbr), highlight:learning.highlights[abbr] || null};
}).sort((a,b) => a.name.localeCompare(b.name, 'en'));
if (entries.length !== 88 || entries.flatMap(item => item.charts).length !== 89) throw new Error('Incomplete atlas');
const data = {metadata:iau.metadata, learning, entries};
fs.writeFileSync(path.join(root, 'atlas-data.js'), '// Generated by scripts/build-atlas.cjs from the reviewed local JSON sources.\nwindow.STAR_ATLAS_DATA = ' + JSON.stringify(data) + ';\n');
// Keep the service worker's required-file list synchronized with the full atlas.
const swPath = path.join(root, 'sw.js');
const sw = fs.readFileSync(swPath, 'utf8');
const assets = ['atlas-data.js','atlas.js','atlas.css','ATLAS_REFERENCES.md', ...entries.flatMap(item => item.charts.map(chart => chart.localPath))];
const block = '// ATLAS ASSETS START\n' + assets.map(file => `  "./${file}",`).join('\n') + '\n  // ATLAS ASSETS END';
if (!sw.includes('// ATLAS ASSETS START')) throw new Error('Missing atlas asset markers in sw.js');
fs.writeFileSync(swPath, sw.replace(/\/\/ ATLAS ASSETS START[\s\S]*?\/\/ ATLAS ASSETS END/, block));
